#!/usr/bin/env python3
"""Refresh release metadata for the existing symbol names; never bundle glyphs."""

import argparse
import collections
import pathlib
import plistlib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metadata", type=pathlib.Path, help="SF Symbols name_availability.plist")
    args = parser.parse_args()
    source = pathlib.Path(__file__).resolve().parent.parent / "Shared/SFSymbolNames.swift"
    text = source.read_text()
    names = text.split('private static let names = """', 1)[1].split('"""', 1)[0].split()
    metadata = plistlib.loads(args.metadata.read_bytes())
    groups = collections.defaultdict(list)
    unknown_names = []
    for name in names:
        release = metadata["symbols"].get(name)
        if release is None:
            unknown_names.append(name)
            continue
        platforms = metadata["year_to_release"][release]
        mac_version = tuple(map(int, platforms["macOS"].split(".")))
        ios_version = tuple(map(int, platforms["iOS"].split(".")))
        # The apps share a minimum release of 26. Future cohorts must agree.
        if mac_version > (26, 0) or ios_version > (26, 0):
            if mac_version != ios_version:
                raise ValueError(f"Platform-specific availability needs handling: {name}")
            if len(mac_version) != 2:
                raise ValueError(f"Availability needs a major and minor release: {name}")
            groups[mac_version].append(name)

    marker = "    // BEGIN GENERATED SYMBOL AVAILABILITY\n"
    generated = marker
    generated += "    // Generated by scripts/update-symbol-availability.py from SF Symbols metadata.\n"
    generated += "    // Names absent from that metadata still use the platform availability check.\n"
    generated += "    private static let laterReleases: [(major: Int, minor: Int, names: Set<String>)] = [\n"
    for (major, minor), symbols in sorted(groups.items()):
        generated += f"        ({major}, {minor}, Set(\"\"\"\n"
        generated += "".join(f"        {name}\n" for name in symbols)
        generated += '        """.split(separator: "\\n").map(String.init))),\n'
    generated += "    ]\n\n    private static let unknownNames = Set(\"\"\"\n"
    generated += "".join(f"    {name}\n" for name in unknown_names)
    generated += '    """.split(separator: "\\n").map(String.init))\n'
    generated += "    // END GENERATED SYMBOL AVAILABILITY\n"
    if marker in text:
        prefix, rest = text.split(marker, 1)
        _, suffix = rest.split("    // END GENERATED SYMBOL AVAILABILITY\n", 1)
        text = prefix + generated + suffix
    else:
        prefix, suffix = text.rsplit("}", 1)
        text = prefix + "\n" + generated + "}" + suffix
    source.write_text(text)
    print(f"Updated availability for {len(names)} names; {len(unknown_names)} runtime checks remain.")


if __name__ == "__main__":
    main()
